// Har drill ka jawab chhote engine se NIKALTA hai (haath se nahi likhta), isliye galat answer nahi ho sakta.
import fs from "node:fs";
import * as C from "./miniChess.mjs";

const N = C.NAME;
const out = {};
const fail = (m) => { throw new Error(m); };
const flip = (turn) => turn === "b";

/* ---- 1) Hanging pieces (tap) ---- */
const HANG = [
  ["r1bqkb1r/pppp1ppp/2n5/4p3/2B1n3/2N2N2/PPPP1PPP/R1BQK2R w - - 0 1", "f6e4"],
  ["rnbqkb1r/ppp2ppp/4pn2/3N4/2PP4/8/PP2PPPP/R1BQKBNR b - - 0 1", "c3d5"],
  ["r1b1k2r/pp2bppp/2nqpn2/2pp4/3P1B2/2PBPN2/PP3PPP/RN1QK2R w - - 0 1", "d8d6"],
  ["rBbqk2r/pp2bppp/2n1pn2/2pp4/3P4/2PBPN2/PP3PPP/RN1QK2R b - - 0 1", "f4b8"],
  ["r2q1rk1/ppp2ppp/2n2n2/3ppb2/3PP3/2NB1N2/PPP2PPP/R1BQ1RK1 w - - 0 1", "e6f5"],
];
out.hanging = HANG.map(([fen, last], i) => {
  const bad = C.validPosition(fen); if (bad) fail(`hang ${i}: ${bad}`);
  const { b, turn } = C.parse(fen);
  const hs = C.hangingSet(b);
  if (hs.length !== 1) fail(`hang ${i}: expected 1 hanging, got ${hs.length}`);
  const h = hs[0], p = b[h.sq], a = h.attackers[0];
  const why = h.defenders.length === 0
    ? `The ${N[p.t]} on ${C.sqName(h.sq)} is attacked by the ${N[b[a].t]} on ${C.sqName(a)}, and nothing defends it.`
    : `The ${N[p.t]} on ${C.sqName(h.sq)} is attacked by a ${N[b[a].t]}, which is worth less. Even defended, it loses.`;
  return { id: `hanging-${i + 1}`, type: "tap", fen, flip: flip(turn), prompt: "Tap the hanging piece.",
    answers: [C.sqName(h.sq)], why, lastMove: { from: last.slice(0, 2), to: last.slice(2, 4) } };
});

/* ---- 2) Free piece or trap? (choice) ---- */
const CHOICE = [
  ["4k3/8/8/3n4/8/5B2/8/4K3 w - - 0 1", "f3", "d5"],
  ["2b1k3/1p6/8/8/8/8/1Q6/4K3 w - - 0 1", "b2", "b7"],
  ["4k3/8/2p5/3n4/4P3/8/8/4K3 w - - 0 1", "e4", "d5"],
  ["4k3/8/3p4/4p3/5B2/8/8/4K3 w - - 0 1", "f4", "e5"],
  ["r3k3/p7/8/8/8/8/8/R3K3 w - - 0 1", "a1", "a7"],
];
out["safe-or-trap"] = CHOICE.map(([fen, from, to], i) => {
  const bad = C.validPosition(fen); if (bad) fail(`choice ${i}: ${bad}`);
  const { b, turn } = C.parse(fen);
  const v = C.captureVerdict(b, C.sqIdx(from), C.sqIdx(to));
  if (!v) fail(`choice ${i}: capture not legal`);
  const safe = v.net > 0;
  const why = safe
    ? v.recapture
      ? `They can take back, but you still win a ${N[v.captured]} for a ${N[v.moved]}.`
      : `Nothing can take back. You win the ${N[v.captured]} for free.`
    : `They simply take back. You lose a ${N[v.moved]} for a ${N[v.captured]}.`;
  return { id: `safe-or-trap-${i + 1}`, type: "choice", fen, flip: flip(turn), prompt: "Take it?",
    arrow: { from, to }, answers: [safe ? "take" : "trap"], why };
});

/* ---- 3) Forks (move) ---- */
const FORKS = [
  "2r1k3/8/8/8/4N3/8/8/4K3 w - - 0 1",
  "4k3/8/8/8/3n4/8/8/R3K3 b - - 0 1",
  "6k1/6pp/r7/8/8/8/2Q5/6K1 w - - 0 1",
  "3q3r/8/8/4N3/8/8/8/4K2k w - - 0 1",
  "4k3/8/8/2r1q3/8/3P4/8/3R2K1 w - - 0 1",
];
out.forks = FORKS.map((fen, i) => {
  const bad = C.validPosition(fen); if (bad) fail(`fork ${i}: ${bad}`);
  const { b, turn } = C.parse(fen);
  const fm = C.forkMoves(b, turn);
  if (!fm.length) fail(`fork ${i}: no fork`);
  const f = fm[0];
  const nb = C.apply(b, f.m);
  const names = f.targets.map((t) => N[nb[t].t]);
  const why = `The ${N[f.piece]} on ${C.sqName(f.m.to)} attacks the ${names[0]} and the ${names[1]} at once. You win one of them.`;
  return { id: `forks-${i + 1}`, type: "move", fen, flip: flip(turn), prompt: "Find the fork.",
    answers: fm.map((x) => C.uci(x.m)), why };
});

/* ---- 4) Back-rank mates (move) ---- */
const MATES = [
  "6k1/5ppp/8/8/8/8/5PPP/3R2K1 w - - 0 1",
  "r5k1/5ppp/8/8/8/8/5PPP/R5K1 w - - 0 1",
  "2r3k1/5ppp/8/8/8/8/PP3PPP/2R3K1 w - - 0 1",
  "3r2k1/5ppp/8/8/8/8/5PPP/6K1 b - - 0 1",
  "6k1/5ppp/8/3Q4/8/8/5PPP/6K1 w - - 0 1",
];
out["back-rank"] = MATES.map((fen, i) => {
  const bad = C.validPosition(fen); if (bad) fail(`mate ${i}: ${bad}`);
  const { b, turn } = C.parse(fen);
  const mm = C.mateMoves(b, turn);
  if (!mm.length) fail(`mate ${i}: no mate`);
  return { id: `back-rank-${i + 1}`, type: "move", fen, flip: flip(turn), prompt: "Mate in 1.",
    answers: mm.map(C.uci), why: "The king is boxed in by its own pawns, so the check on the back rank is mate." };
});

const header = "// GENERATED by tools/gen-lessons.mjs. Haath se mat badlo; tools/ mein positions badal ke dobara chalao.\n";
fs.writeFileSync(new URL("../src/features/coach/drills.generated.js", import.meta.url), `${header}export const DRILLS = ${JSON.stringify(out, null, 1)};\n`);
for (const [k, v] of Object.entries(out)) console.log(k, v.length, "drills; answers:", v.map((d) => d.answers.join("/")).join(" | "));
